local digits="0123456789abcdef"
local function encode(v)
  local t=type(v)
  if t=="nil" then return "nil" end
  if t=="boolean" then return tostring(v) end
  if t=="number" then return "n:"..tostring(v) end
  if t=="string" then
    local s="s:"
    for i=1,#v do local b=string.byte(v,i); local h=math.floor(b/16); local l=b%16; s=s..string.sub(digits,h+1,h+1)..string.sub(digits,l+1,l+1) end
    return s
  end
  return t
end
