#!/usr/bin/env python3
"""Explicit, compiler-independent MessagePack oracle experiment (no gate caller).

All builds and generated bytes live in --scratch. See API.md and RESULTS.md.
"""
import argparse
import json
import math
from pathlib import Path
import random
import struct
import subprocess
import time

import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from compiler_cache import add_arguments as cache_arguments, flags as cache_flags

MASK = (1 << 64) - 1
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]


def require(condition, message):
    if not condition:
        raise AssertionError(message)


def command(args, **kwargs):
    started = time.monotonic()
    result = subprocess.run([str(x) for x in args], capture_output=True, **kwargs)
    require(result.returncode == 0,
            f'{args[0]} exited {result.returncode}: {result.stderr.decode(errors="replace")}')
    return result.stdout, time.monotonic() - started


def request(op, value=0, data=b''):
    return (op, value & MASK, data)


def wire(records):
    return b''.join(struct.pack('<BQQ', op, n, len(data)) + data
                    for op, n, data in records) + bytes(17)


def frames(raw, count):
    result = []
    cursor = 0
    for _ in range(count):
        require(cursor + 8 <= len(raw), 'missing response length')
        size, = struct.unpack_from('<Q', raw, cursor)
        cursor += 8
        require(cursor + size <= len(raw), 'truncated response payload')
        result.append(raw[cursor:cursor + size])
        cursor += size
    require(cursor == len(raw), 'unexpected extra responses')
    return result


def batch(program, records):
    raw, seconds = command([program], input=wire(records), timeout=60)
    return frames(raw, len(records)), seconds


def integer(n):
    if n >= 0:
        if n <= 127:
            return bytes([n])
        for tag, fmt, limit in [(0xcc, '>B', 255), (0xcd, '>H', 65535),
                                (0xce, '>I', (1 << 32) - 1), (0xcf, '>Q', MASK)]:
            if n <= limit:
                return bytes([tag]) + struct.pack(fmt, n)
    else:
        if n >= -32:
            return bytes([n & 255])
        for tag, fmt, lower in [(0xd0, '>b', -128), (0xd1, '>h', -32768),
                                (0xd2, '>i', -(1 << 31)), (0xd3, '>q', -(1 << 63))]:
            if n >= lower:
                return bytes([tag]) + struct.pack(fmt, n)
    raise AssertionError('integer outside wire domain')


def number(bits):
    value, = struct.unpack('>d', struct.pack('>Q', bits))
    if math.isfinite(value) and -(1 << 63) <= value < (1 << 63) and value.is_integer():
        return integer(int(value))
    try:
        narrow = struct.pack('>f', value)
    except OverflowError:
        narrow = struct.pack('>f', math.copysign(math.inf, value))
    if struct.unpack('>f', narrow)[0] == value:
        return b'\xca' + narrow
    return b'\xcb' + struct.pack('>Q', bits)


def counted(size, tags, fix=None):
    if fix is not None and size < fix[1]:
        return bytes([fix[0] | size])
    for tag, fmt, limit in tags:
        if size <= limit:
            return bytes([tag]) + struct.pack(fmt, size)
    raise AssertionError('length outside wire domain')


def expected_write(record):
    op, n, data = record
    if op == 1:
        return b'\xc0'
    if op == 2:
        return b'\xc3' if n else b'\xc2'
    if op == 3:
        return integer(n)
    if op == 4:
        return integer(n if n < (1 << 63) else n - (1 << 64))
    if op == 5:
        return number(n)
    if op == 6:
        return b'\xca' + struct.pack('>I', n & 0xffffffff)
    if op == 7:
        return b'\xcb' + struct.pack('>Q', n)
    if op == 8:
        return counted(len(data), [(0xd9, '>B', 255), (0xda, '>H', 65535),
                                   (0xdb, '>I', 0xffffffff)], (0xa0, 32)) + data
    if op == 9:
        return counted(len(data), [(0xc4, '>B', 255), (0xc5, '>H', 65535),
                                   (0xc6, '>I', 0xffffffff)]) + data
    if op == 10:
        if len(data) in (1, 2, 4, 8, 16):
            header = bytes([0xd4 + (1, 2, 4, 8, 16).index(len(data))])
        else:
            header = counted(len(data), [(0xc7, '>B', 255), (0xc8, '>H', 65535),
                                         (0xc9, '>I', 0xffffffff)])
        return header + bytes([n & 255]) + data
    if op in (11, 12):
        return counted(n, [(0xdc if op == 11 else 0xde, '>H', 65535),
                           (0xdd if op == 11 else 0xdf, '>I', 0xffffffff)],
                       (0x90 if op == 11 else 0x80, 16))
    if op == 13:
        return b'\x92\x81' + expected_write(request(8, data=data)) + b'\x92\x2a\xc3\xc2'
    raise AssertionError('unknown writer operation')


def event(tag, start, end, kind, value=0, first=0, last=0):
    return struct.pack('<BBQQBQQQ', 0, tag, start, end, kind, value & MASK, first, last)


def expected_decode(data, offset=0):
    """Independent wire oracle; errors name the incomplete segment, not EOF."""
    if offset > len(data):
        return b'\x04' + struct.pack('<Q', offset)
    if offset == len(data):
        return b'\x01'
    tag = data[offset]
    at = offset + 1

    def need(count):
        if len(data) - at < count:
            return b'\x02' + struct.pack('<QQQQ', offset, at, count, len(data) - at)
        return None

    if tag < 128:
        return event(tag, offset, at, 3, tag)
    if tag >= 224:
        return event(tag, offset, at, 4, tag - 256)
    if 128 <= tag < 160:
        return event(tag, offset, at, 10 if tag < 144 else 9, tag & 15)
    if tag == 193:
        return b'\x03' + struct.pack('<Q', offset)
    if 192 <= tag <= 195:
        return event(tag, offset, at, {192: 0, 194: 1, 195: 2}[tag])
    numeric = {204: ('>B', 3), 205: ('>H', 3), 206: ('>I', 3), 207: ('>Q', 3),
               208: ('>b', 4), 209: ('>h', 4), 210: ('>i', 4), 211: ('>q', 4),
               202: ('>I', 5), 203: ('>Q', 6), 220: ('>H', 9), 221: ('>I', 9),
               222: ('>H', 10), 223: ('>I', 10)}
    if tag in numeric:
        fmt, kind = numeric[tag]
        width = struct.calcsize(fmt)
        error = need(width)
        if error:
            return error
        value, = struct.unpack_from(fmt, data, at)
        return event(tag, offset, at + width, kind, value)
    if 160 <= tag <= 191:
        size, kind = tag & 31, 7
    elif 212 <= tag <= 216:
        size, kind = 1 << (tag - 212), 11
    else:
        fmt, kind = {196: ('>B', 8), 197: ('>H', 8), 198: ('>I', 8),
                     199: ('>B', 11), 200: ('>H', 11), 201: ('>I', 11),
                     217: ('>B', 7), 218: ('>H', 7), 219: ('>I', 7)}[tag]
        width = struct.calcsize(fmt)
        error = need(width)
        if error:
            return error
        size, = struct.unpack_from(fmt, data, at)
        at += width
    type_code = 0
    if kind == 11:
        error = need(1)
        if error:
            return error
        type_code = data[at]
        at += 1
    error = need(size)
    if error:
        return error
    return event(tag, offset, at + size, kind, type_code, at, at + size)


def equal(actual, expected, label):
    require(actual == expected,
            f'{label}: actual={actual[:80].hex()} expected={expected[:80].hex()}')


def controls():
    """Demonstrate that comparison and framing checks reject faulty responses."""
    mutations = [
        lambda: equal(b'\xcc\x81', b'\xcc\x80', 'changed writer byte'),
        lambda: equal(b'\xcc', b'\xcc\x80', 'missing writer byte'),
        lambda: frames(b'', 1),
        lambda: frames(struct.pack('<Q', 2) + b'x', 1),
        lambda: frames(struct.pack('<Q', 1) + b'xx', 1),
    ]
    valid = event(0xcc, 0, 2, 3, 128)
    for index in (0, 1, 2, 10, 18, 19, 27, 35):
        altered = bytearray(valid)
        altered[index] ^= 1
        mutations.append(lambda a=bytes(altered): equal(a, valid, 'changed token field'))
    trunc = b'\x02' + struct.pack('<QQQQ', 7, 9, 4, 2)
    for index in (0, 1, 9, 17, 25):
        altered = bytearray(trunc)
        altered[index] ^= 1
        mutations.append(lambda a=bytes(altered): equal(a, trunc, 'changed truncation field'))
    for check in mutations:
        try:
            check()
        except AssertionError:
            continue
        raise AssertionError('negative control was accepted')
    return len(mutations)


def suite(wf, reference, generated):
    rng = random.Random(0x4d5041434b)
    records = [request(1), request(2), request(2, 1)]
    boundaries = [-2**63, -2**31-1, -2**31, -32769, -32768, -129, -128,
                  -33, -32, -1, 0, 1, 127, 128, 255, 256, 65535, 65536,
                  2**32-1, 2**32, 2**63-1]
    records += [request(4, n) for n in boundaries]
    for bits in [0, 1 << 63, 0x7ff0000000000000, 0xfff0000000000000,
                 1, 0x0010000000000000, 0xc3e0000000000000]:
        records.append(request(5, bits))
    for value in [1.5, 1.1, -0.5, 16777217.5, 2**53-1, 2**53, -2**63]:
        records.append(request(5, struct.unpack('<Q', struct.pack('<d', value))[0]))
    sizes = [0, 1, 2, 4, 8, 16, 31, 32, 255, 256, 65535, 65536]
    records += [request(8, data=bytes((i * 37) & 255 for i in range(n))) for n in sizes]
    for count in [0, 1, 15, 16, 65535, 65536, 0xffffffff]:
        records += [request(11, count), request(12, count)]
    for i in range(generated):
        mode = i % 5
        if mode == 0:
            records.append(request(4, rng.randrange(-2**63, 2**63)))
        elif mode == 1:
            records.append(request(3, rng.randrange(2**63)))
        elif mode == 2:
            bits = (rng.getrandbits(1) << 63) | (rng.randrange(1086) << 52) | rng.getrandbits(52)
            records.append(request(5, bits))
        elif mode == 3:
            # Finite fractional f32 values select cmsgpack's float32 branch.
            n = rng.uniform(-1000000, 1000000)
            f32 = struct.unpack('<f', struct.pack('<f', n))[0]
            records.append(request(5, struct.unpack('<Q', struct.pack('<d', f32))[0]))
        else:
            records.append(request(8, data=rng.randbytes(rng.randrange(401))))
    actual, wf_seconds = batch(wf, records)
    oracle, reference_seconds = batch(reference, records)
    for i, (record, ours, theirs) in enumerate(zip(records, actual, oracle)):
        equal(ours, b'\x55' + theirs, f'cmsgpack value {i} {record[:2]}')
        equal(ours, b'\x55' + expected_write(record), f'independent writer {i}')

    extras = [request(3, n) for n in [2**63, MASK]]
    extras.append(request(13, data=b'k'))
    # These C float-to-int64 casts are undefined; check the total policy independently.
    extras += [request(5, bits) for bits in [0x43e0000000000000,
               0x7fefffffffffffff, 0xffefffffffffffff,
               0x7ff8000000001234, 0xfff8000000004321, 0x7ff0000000001234]]
    for n in sizes:
        data = rng.randbytes(n)
        extras += [request(9, data=data)]
        extras += [request(10, t, data) for t in [0, 127, 128, 255]]
    extras += [request(op, bits) for op, words in [
        (6, [0, 0x80000000, 0x7f800000, 0xff800000, 0x7fc12345, 0x7f812345, 1]),
        (7, [0, 1 << 63, 0x7ff8000000001234, 0x7ff0000000001234, 1])]
        for bits in words]
    extra_outputs, _ = batch(wf, extras)
    for i, (record, ours) in enumerate(zip(extras, extra_outputs)):
        equal(ours, b'\x55' + expected_write(record), f'full-family writer {i}')

    # Decode each writer result at a nonzero offset, then at its exact end.
    decodes = []
    for output in actual + extra_outputs:
        data = b'prefix' + output[1:]
        decodes += [request(20, 6, data), request(20, len(data), data)]
    # Selected cuts also cover str/bin/ext32 payloads and growth-size boundaries.
    large_prefix_checks = 0
    for output in actual + extra_outputs:
        data = output[1:]
        if len(data) > 1 and data[0] not in list(range(128, 160)) + [220, 221, 222, 223]:
            for cut in sorted({1, len(data) - 1}):
                decodes.append(request(20, 2, b'ab' + data[:cut]))
                large_prefix_checks += 1
    # Every tag, including non-minimal widths and all signedness boundaries.
    all_formats = []
    for tag in range(256):
        if tag < 160 or tag >= 224 or tag in (192, 193, 194, 195):
            data = bytes([tag])
        elif tag < 192:
            data = bytes([tag]) + bytes(range(tag & 31))
        elif tag in (196, 197, 198, 199, 200, 201, 217, 218, 219):
            width = {196: 1, 197: 2, 198: 4, 199: 1, 200: 2, 201: 4,
                     217: 1, 218: 2, 219: 4}[tag]
            data = bytes([tag]) + (3).to_bytes(width, 'big')
            if tag in (199, 200, 201):
                data += b'\x80'
            data += b'\x00\xff\x7f'
        elif 212 <= tag <= 216:
            data = bytes([tag, 255]) + bytes(range(1 << (tag - 212)))
        else:
            width = {202: 4, 203: 8, 204: 1, 205: 2, 206: 4, 207: 8,
                     208: 1, 209: 2, 210: 4, 211: 8, 220: 2, 221: 4,
                     222: 2, 223: 4}[tag]
            data = bytes([tag]) + bytes([255]) * width
        all_formats.append(data)
        decodes.append(request(20, 0, data))
    # Every nonempty proper prefix of every multi-byte format, at two offsets.
    truncations = 0
    for data in all_formats:
        for cut in range(1, len(data)):
            for prefix in (b'', b'\x00\xc0\xff'):
                decodes.append(request(20, len(prefix), prefix + data[:cut]))
                truncations += 1
    # Large declared lengths, zero-length extension, and out-of-range offsets.
    malformed = [b'\xdb\xff\xff\xff\xff', b'\xc6\xff\xff\xff\xff',
                 b'\xc9\xff\xff\xff\xff', b'\xc7\x00', b'\xc7\x00\xff']
    decodes += [request(20, 0, data) for data in malformed]
    decodes += [request(20, 1, b''), request(20, MASK, b'\xc0'), request(20, 0, b'')]
    # Nested containers are explicit token streams; no child is skipped.
    nested = b'\x92\x81\xa1k\x92\x2a\xc3\xc2'
    offsets = [0, 1, 2, 4, 5, 6, 7, 8]
    decodes += [request(20, at, nested) for at in offsets]
    # Arbitrary bytes exercise malformed length fields and every offset domain.
    for _ in range(1000):
        data = rng.randbytes(rng.randrange(40))
        offset = rng.randrange(len(data) + 3)
        decodes.append(request(20, offset, data))
    decoded, decode_seconds = batch(wf, decodes)
    for i, (record, ours) in enumerate(zip(decodes, decoded)):
        _, offset, data = record
        equal(ours, expected_decode(data, offset), f'decoder {i}, offset {offset}')
    return dict(generated_values=generated, cmsgpack_comparisons=len(records),
                full_family_writer_checks=len(extras),
                round_trip_records=len(actual) + len(extra_outputs),
                decoding_checks=len(decodes), format_tags=256,
                truncated_checks=truncations, selected_prefix_checks=large_prefix_checks,
                arbitrary_byte_checks=1000, negative_controls=controls(),
                wf_writer_seconds=round(wf_seconds, 6),
                reference_seconds=round(reference_seconds, 6),
                wf_decoder_seconds=round(decode_seconds, 6))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--compiler', type=Path, required=True)
    parser.add_argument('--redis-src', type=Path, required=True,
                        help='Redis deps/lua/src containing lua_cmsgpack.c and Lua headers')
    parser.add_argument('--lua-lib', type=Path, required=True, help='bundled Lua liblua.a')
    parser.add_argument('--scratch', type=Path, required=True)
    parser.add_argument('--generated', type=int, default=3000)
    cache_arguments(parser, 'msgpack', timing=True)
    args = parser.parse_args()
    require(args.generated >= 0, 'generated count must be nonnegative')
    scratch = args.scratch.resolve()
    require(not scratch.is_relative_to(ROOT), 'scratch must be outside the repository')
    scratch.mkdir(parents=True, exist_ok=True)
    wf, reference = scratch / 'msgpack-check', scratch / 'msgpack-reference'
    _, build = command([args.compiler.resolve(), '--graph', HERE / 'modules.wfg',
                        '--entry', 'check', '-o', wf] + cache_flags(args), timeout=900)
    _, c_build = command(['cc', '-O2', '-I' + str(args.redis_src.resolve()),
                          HERE / 'reference.c', args.lua_lib.resolve(), '-lm', '-o', reference],
                         timeout=60)
    results = suite(wf, reference, args.generated)
    results.update(wf_build_seconds=round(build, 6), c_build_seconds=round(c_build, 6))
    (scratch / 'results.json').write_text(json.dumps(results, indent=2) + '\n')
    print(json.dumps(results, indent=2))


if __name__ == '__main__':
    main()
